for (const sub of newSubjects) {
  newQuestionsCode += `  ${sub.id}: [\n`;
  sub.questions.forEach((q, idx) => {
    const qId = `${sub.prefix}_q${idx + 1}`;
    const opts = [
      { id: "opt_1", text: q.ans, isCorrect: true },
      { id: "opt_2", text: q.wrong[0], isCorrect: false },
      { id: "opt_3", text: q.wrong[1], isCorrect: false },
      { id: "opt_4", text: q.wrong[2], isCorrect: false },
    ];
    // Deterministic shuffle
    const s = ((idx * 7) + 3) % 4;
    const shuffled = [...opts.slice(s), ...opts.slice(0, s)];

    newQuestionsCode += `    {\n`;
    newQuestionsCode += `      id: "${qId}",\n`;
    newQuestionsCode += `      category: "${sub.category}",\n`;
    newQuestionsCode += `      skillTag: "${sub.skillTag}",\n`;
    newQuestionsCode += `      subTopic: "${q.sub}",\n`;
    newQuestionsCode += `      difficulty: "${q.diff}",\n`;
    newQuestionsCode += `      questionText: ${JSON.stringify(q.q)},\n`;
    newQuestionsCode += `      questionType: "single_choice",\n`;
    newQuestionsCode += `      displayOrder: ${idx + 1},\n`;
    newQuestionsCode += `      explanation: ${JSON.stringify(q.exp)},\n`;
    newQuestionsCode += `      options: [\n`;
    for (const opt of shuffled) {
      newQuestionsCode += `        { id: "${opt.id}", text: ${JSON.stringify(opt.text)}, scoreWeight: ${opt.isCorrect ? 1.0 : 0.0}, isCorrect: ${opt.isCorrect} },\n`;
    }
    newQuestionsCode += `      ],\n`;
    newQuestionsCode += `    },\n`;
  });
  newQuestionsCode += `  ],\n`;
}

